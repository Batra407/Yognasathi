function fetchAllStateSchemes() {
  const rawDir = path.join(process.cwd(), 'data', 'raw', 'state_schemes');
  if (!fs.existsSync(rawDir)) {
    fs.mkdirSync(rawDir, { recursive: true });
  }

  // 1. Save Pilot Snapshots
  const pilotPayload = {
    metadata: {
      generatedAt: new Date().toISOString(),
      pilotStates: ['Maharashtra', 'Rajasthan'],
      totalRecords: PILOT_SCHEMES_MAHARASHTRA.length + PILOT_SCHEMES_RAJASTHAN.length
    },
    schemes: [...PILOT_SCHEMES_MAHARASHTRA, ...PILOT_SCHEMES_RAJASTHAN]
  };

  const pilotPath = path.join(rawDir, 'pilot_state_schemes_raw.json');
  fs.writeFileSync(pilotPath, JSON.stringify(pilotPayload, null, 2), 'utf8');
  console.log(`[PASS] Pilot State Schemes Raw Snapshot written to: ${pilotPath} (${pilotPayload.schemes.length} records)`);

  // 2. Save All-India Snapshots
  const allSchemes = [
    ...PILOT_SCHEMES_MAHARASHTRA,
    ...PILOT_SCHEMES_RAJASTHAN,
    ...ALL_OTHER_STATES_AND_UTS_SCHEMES
  ];

  const allIndiaPayload = {
    metadata: {
      generatedAt: new Date().toISOString(),
      totalRecords: allSchemes.length,
      scope: 'All 28 States & 8 Union Territories'
    },
    schemes: allSchemes
  };

  const allIndiaPath = path.join(rawDir, 'all_state_schemes_raw.json');
  fs.writeFileSync(allIndiaPath, JSON.stringify(allIndiaPayload, null, 2), 'utf8');
  console.log(`[PASS] All-India State Schemes Raw Snapshot written to: ${allIndiaPath} (${allSchemes.length} records)`);

  return {
    pilotCount: pilotPayload.schemes.length,
    allIndiaCount: allSchemes.length
  };
}

if (require.main === module) {
  fetchAllStateSchemes();
}

module.exports = {
  PILOT_SCHEMES_MAHARASHTRA,
  PILOT_SCHEMES_RAJASTHAN,
  ALL_OTHER_STATES_AND_UTS_SCHEMES,
  fetchAllStateSchemes
};
